/**
 * Renders the AmbientMind mark to PNG without an image dependency, then emits
 * it as base64 in a TS module. Base64 rather than files because the tray icon
 * has to load identically from source, from out/, and from inside an asar.
 *
 *   node scripts/make-icons.cjs
 */
const { deflateSync } = require('node:zlib')
const { writeFileSync, mkdirSync } = require('node:fs')
const { join } = require('node:path')

const SUPERSAMPLE = 4

/**
 * Coverage of one pixel, 0..1, averaged over a 4x4 grid. Returns both the mark
 * (ring + centre dot) and the disc behind it, so the app icon can be opaque
 * while the tray icon stays a transparent glyph.
 */
function coverage(px, py, size, padding) {
  const r = size / 2
  const usable = r * (1 - padding)
  const outer = usable * 0.94
  const inner = usable * 0.56
  const dot = usable * 0.2

  let mark = 0
  let disc = 0
  for (let sy = 0; sy < SUPERSAMPLE; sy++) {
    for (let sx = 0; sx < SUPERSAMPLE; sx++) {
      const x = px + (sx + 0.5) / SUPERSAMPLE - r
      const y = py + (sy + 0.5) / SUPERSAMPLE - r
      const d = Math.hypot(x, y)
      if ((d <= outer && d >= inner) || d <= dot) mark++
      if (d <= usable) disc++
    }
  }
  const total = SUPERSAMPLE * SUPERSAMPLE
  return { mark: mark / total, disc: disc / total }
}

function crc32(buf) {
  let crc = ~0
  for (let i = 0; i < buf.length; i++) {
    crc ^= buf[i]
    for (let bit = 0; bit < 8; bit++) {
      crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1))
    }
  }
  return ~crc >>> 0
}

function chunk(type, data) {
  const length = Buffer.alloc(4)
  length.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([length, body, crc])
}

/**
 * 8-bit RGBA PNG. The tray variant is a white glyph on transparency so Windows
 * can tint it per theme; the app variant paints the glyph on a dark disc so it
 * is visible against a light background.
 */
function renderPng(size, variant = 'tray') {
  const app = variant === 'app'
  const padding = app ? 0.06 : 0
  const raw = Buffer.alloc(size * (size * 4 + 1))
  let offset = 0
  for (let y = 0; y < size; y++) {
    raw[offset++] = 0 // filter: none
    for (let x = 0; x < size; x++) {
      const { mark, disc } = coverage(x, y, size, padding)
      if (!app) {
        raw[offset++] = 255
        raw[offset++] = 255
        raw[offset++] = 255
        raw[offset++] = Math.round(mark * 255)
        continue
      }
      // Composite the white mark over the dark disc, premultiplied by coverage.
      const base = 0x16
      const value = Math.round(base * (1 - mark) + 255 * mark)
      raw[offset++] = value
      raw[offset++] = value
      raw[offset++] = value
      raw[offset++] = Math.round(Math.max(disc, mark) * 255)
    }
  }

  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 6 // colour type: RGBA
  ihdr[10] = 0
  ihdr[11] = 0
  ihdr[12] = 0

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0))
  ])
}

const root = join(__dirname, '..')
const buildDir = join(root, 'build')
mkdirSync(buildDir, { recursive: true })

// The installer wants a large square; electron-builder downscales from it.
writeFileSync(join(buildDir, 'icon.png'), renderPng(256, 'app'))

const tray16 = renderPng(16).toString('base64')
const tray32 = renderPng(32).toString('base64')

writeFileSync(
  join(root, 'electron', 'assets', 'trayIcon.ts'),
  `// Generated by scripts/make-icons.cjs. Do not edit by hand.
export const TRAY_ICON_16 = '${tray16}'
export const TRAY_ICON_32 = '${tray32}'
`
)

console.log('wrote build/icon.png and electron/assets/trayIcon.ts')
