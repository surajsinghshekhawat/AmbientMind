/**
 * Writes THIRD_PARTY_NOTICES.md: every open-source package that ships inside
 * AmbientMind, with its licence text. MIT, BSD and Apache all require the
 * notice to travel with the binary, and the build copies this file in.
 *
 * What ships:
 *   - production dependencies, which electron-builder copies into the app;
 *   - the libraries Vite bundles into the windows. They are devDependencies
 *     because nothing loads them at runtime, but their code is in out/.
 *
 * `--check` writes nothing and fails when the file is stale or when a package
 * has a licence nobody has reviewed (copyleft, or none at all).
 */
const { existsSync, readFileSync, readdirSync, writeFileSync } = require('node:fs')
const { join } = require('node:path')

const root = join(__dirname, '..')
const output = join(root, 'THIRD_PARTY_NOTICES.md')

/** Bundled into the windows, with everything they depend on at runtime. */
const RENDERER_ROOTS = ['react', 'react-dom', '@base-ui/react', 'lucide-react', 'thinking-orbs']
/** Only its CSS reset ends up in the build; its own dependencies are build tools. */
const RENDERER_ALONE = ['tailwindcss']

const PERMISSIVE = /^\(?(MIT|ISC|BSD-[23]-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|Unlicense|CC0-1\.0|Python-2\.0)(\s+(OR|AND)\s+\(?(MIT|ISC|BSD-[23]-Clause|Apache-2\.0|WTFPL|0BSD|CC0-1\.0)\)?)*\)?$/

/**
 * Licences that are not on the permissive list but were read and accepted.
 * Keyed by package name so a new version with a different licence still fails.
 */
const REVIEWED = {
  // Apache-2.0 in the LICENSE.txt the field points to.
  flatbuffers: 'Apache-2.0',
  // "MIT OR Apache" is not SPDX; the repository is dual MIT / Apache-2.0.
  'sqlite-vec': 'MIT OR Apache-2.0'
}

/** Platform builds (sqlite-vec-darwin-arm64) share the main package's review. */
function reviewed(name) {
  return REVIEWED[name] ?? REVIEWED[name.replace(/-(darwin|linux|windows)-[a-z0-9]+$/, '')]
}

const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8')).packages

/** Node's lookup: the nearest node_modules above `from` that has `name`. */
function resolve(name, from) {
  let base = from
  for (;;) {
    const candidate = `${base ? `${base}/` : ''}node_modules/${name}`
    if (lock[candidate]) return candidate
    if (!base) return null
    const cut = base.lastIndexOf('/node_modules/')
    base = cut === -1 ? '' : base.slice(0, cut)
  }
}

const shipped = new Set()

for (const [path, entry] of Object.entries(lock)) {
  if (path && !entry.dev && existsSync(join(root, path, 'package.json'))) shipped.add(path)
}

function walk(path) {
  if (!path || shipped.has(path) || !existsSync(join(root, path, 'package.json'))) return
  shipped.add(path)
  const entry = lock[path]
  for (const dep of Object.keys({ ...entry.dependencies, ...entry.optionalDependencies })) walk(resolve(dep, path))
}
for (const name of RENDERER_ROOTS) walk(resolve(name, ''))
for (const name of RENDERER_ALONE) {
  const path = resolve(name, '')
  if (path) shipped.add(path)
}

function licenceText(dir) {
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i.test(name))
  return file ? readFileSync(join(dir, file), 'utf8').trim() : null
}

const packages = new Map()
for (const path of shipped) {
  const dir = join(root, path)
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const key = `${pkg.name}@${pkg.version}`
  if (packages.has(key)) continue
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? lock[path].license ?? 'UNKNOWN')
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  packages.set(key, { name: pkg.name, version: pkg.version, license, home: pkg.homepage ?? repo ?? null, text: licenceText(dir) })
}

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const problems = sorted
  .filter((p) => !PERMISSIVE.test(p.license) && reviewed(p.name) === undefined)
  .map((p) => `${p.name}@${p.version}: licence "${p.license}" has not been reviewed`)

const lines = [
  '# Third-party notices',
  '',
  'AmbientMind is free software under the MIT licence below. It is built on the open-source software listed here, each under its own licence.',
  '',
  'Generated by `scripts/notices.cjs` from package-lock.json. Do not edit by hand; run `./dev npm run notices`.',
  '',
  '## AmbientMind',
  '',
  '```text',
  readFileSync(join(root, 'LICENSE'), 'utf8').trim(),
  '```',
  '',
  '## Shipped outside npm',
  '',
  '- **Electron and Chromium.** Their licences ship beside the app as `LICENSE.electron.txt` and `LICENSES.chromium.html` in `AmbientMind.app/Contents/Resources`.',
  '- **libvips** (LGPL-3.0-or-later), with the libraries it links, comes prebuilt inside the `sharp` package that @xenova/transformers depends on. It is a separate, dynamically loaded library in `app.asar.unpacked/node_modules/sharp/vendor`, where its own THIRD-PARTY-NOTICES.md lists every component and licence. You may replace it with your own build. Source: https://github.com/libvips/libvips.',
  '',
  '## Downloaded at runtime, not shipped',
  '',
  '- Whisper speech models (`Xenova/whisper-*.en`, ONNX conversions of OpenAI Whisper, MIT) from Hugging Face, when voice capture first needs one.',
  '- Tesseract English text-recognition data (Apache-2.0) from jsDelivr, when screen reading first needs it.',
  '- Ollama models (by default qwen3 and nomic-embed-text, both Apache-2.0) are installed by you through Ollama, under their own licences.',
  '',
  `## npm packages (${sorted.length})`,
  ''
]
for (const p of sorted) {
  lines.push(`### ${p.name} ${p.version}`, '', `Licence: ${p.license}${p.home ? ` · ${p.home.replace(/^git\+/, '').replace(/\.git$/, '')}` : ''}`, '')
  if (p.text) lines.push('```text', p.text.replace(/```/g, "'''"), '```', '')
  else lines.push('The package ships no licence file; the licence above is from its package.json.', '')
}
const text = `${lines.join('\n').trimEnd()}\n`

if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== text) {
    problems.push('THIRD_PARTY_NOTICES.md is out of date. Run `./dev npm run notices` and commit it.')
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(`[notices] ${problem}`)
    process.exit(1)
  }
  console.log(`[notices] ${sorted.length} packages, all licences reviewed, file up to date.`)
} else {
  writeFileSync(output, text)
  for (const problem of problems) console.warn(`[notices] ${problem}`)
  console.log(`[notices] wrote ${sorted.length} packages to THIRD_PARTY_NOTICES.md`)
  if (problems.length > 0) process.exit(1)
}
